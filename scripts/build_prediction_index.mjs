/** Build the small, fingerprinted startup contract using only the Node runtime. */
import {readFile,writeFile,stat} from 'node:fs/promises'
import {createHash} from 'node:crypto'
import {fileURLToPath} from 'node:url'
import path from 'node:path'
const root=fileURLToPath(new URL('../',import.meta.url)),pub=path.join(root,'public')
const hash=bytes=>createHash('sha256').update(bytes).digest('hex')
const stable=value=>Array.isArray(value)?'['+value.map(stable).join(',')+']':value&&typeof value==='object'?'{'+Object.keys(value).sort().map(key=>JSON.stringify(key)+':'+stable(value[key])).join(',')+'}':JSON.stringify(value)
const read=async p=>JSON.parse(await readFile(path.join(pub,p),'utf8'))
const sites=await read('data/sites.json')
const paths=['data/sites.json','data/missions.json','data/terrain/manifest.json','data/validation/transitions.json',...['barker2021-roi4.json','barker2021-roi4-ensemble.json','barker2021-roi4-matched-ensemble.json'].map(n=>'data/benchmark/'+n)]
const grids=new Map()
for(const site of sites){
 for(const body of ['sun','earth']){
  const p=`data/ephemeris/${site.slug}.${body}.json`;paths.push(p)
  const d=await read(p),grid={start:d.start,stop:d.stop,samples:d.rows.length,stepHours:d.stepHours},key=stable(grid)
  const previous=grids.get(key);grids.set(key,{grid,count:(previous?.count??0)+1})
 }
 paths.push(`data/horizons/${site.slug}.json`,`data/dutycycle/${site.slug}.json`,`data/dispersion/${site.slug}.json`,`data/validation/sites/${site.slug}.json`)
}
const files={}
for(const p of [...new Set(paths)].sort()){
 const full=path.join(pub,p),bytes=await readFile(full)
 files['/'+p]={sha256:hash(bytes),bytes:(await stat(full)).size}
}
const coverage=[...grids.values()].sort((a,b)=>b.count-a.count)[0].grid
const modelPaths=['src/data.ts','src/lib/science.ts','src/lib/attribution.ts','src/lib/visit.ts','src/lib/dsn.ts','src/lib/heightSensitivity.ts','src/lib/transitionValidation.ts','src/architect/solver.ts','src/architect/power.ts','src/architect/thermal.ts','src/architect/dispersion.ts','src/architect/relay.ts','src/architect/comparison.ts','src/architect/robustness.ts','src/architect/missionBrief.ts','src/architect/comparisonContext.ts','src/architect/quickCompare.ts','src/architect/landingDate.ts','scripts/compute_horizons.py','scripts/fetch_ephemeris.py','scripts/build_mission_validation.py']
modelPaths.push('src/lib/surfaceExplorer.ts')
modelPaths.push('src/lib/astronautMotion.ts')
modelPaths.push('src/lib/fieldwork.ts')
modelPaths.push('src/lib/expedition.ts')
modelPaths.push('src/lib/explorationDecision.ts')
modelPaths.push('src/lib/failurePreview.ts')
modelPaths.push('src/lib/guideRepair.ts')
modelPaths.push('src/lib/sensitiveDate.ts')
modelPaths.push('src/lib/scheduleTolerance.ts')
modelPaths.push('src/lib/decisionStory.ts')
modelPaths.push('src/lib/missionConsequence.ts')
modelPaths.push('src/lib/sampleBearing.ts')
modelPaths.push('src/architect/tradeoffs.ts')
const modelFiles={}
for(const p of modelPaths)modelFiles[p]=hash(await readFile(path.join(root,p)))
const modelHash=hash(stable(modelFiles)),version='screening-v2-'+modelHash.slice(0,12)
const core={coverage,files},datasetId=hash(stable(core))
const report={schemaVersion:1,generatedUTC:new Date().toISOString(),datasetId,...core,model:{version,sha256:modelHash,files:modelFiles},analysisObserverHeightM:0,notes:'Fingerprints identify downloaded uncompressed products. Dataset identity excludes generation time and model identity.'}
await writeFile(path.join(pub,'data/prediction-index.json'),JSON.stringify(report,null,2),'utf8')
await writeFile(path.join(root,'src/modelIdentity.ts'),'// Generated by scripts/build_prediction_index.mjs; rebuild after numerical model changes.\n'+`export const MODEL_SHA256 = ${JSON.stringify(modelHash)}\nexport const MODEL_VERSION = ${JSON.stringify(version)}\n`,'utf8')
process.stdout.write(`Prediction index: ${Object.keys(files).length} products; dataset ${datasetId.slice(0,12)}; model ${version}\n`)
